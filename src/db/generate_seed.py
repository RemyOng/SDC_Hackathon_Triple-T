NAMESPACE = uuid.UUID("6f1c2a3e-0871-4c7e-9a0e-6e2b6b9d0871")
OUT = Path(__file__).with_name("seed.sql")


def uid(name: str) -> str:
    """Stable UUIDs so the seed can be re-run without duplicates."""
    return str(uuid.uuid5(NAMESPACE, name))


def q(value) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (list, tuple)):
        return "array[" + ", ".join(q(item) for item in value) + "]::text[]" if value else "'{}'::text[]"
    if isinstance(value, dict):
        return "'" + json.dumps(value).replace("'", "''") + "'::jsonb"
    return "'" + str(value).replace("'", "''") + "'"


def upsert(table: str, row: dict, key: str) -> str:
    columns = ", ".join(row)
    values = ", ".join(q(value) for value in row.values())
    updates = ", ".join(f"{column} = excluded.{column}" for column in row if column != key)
    return f"insert into public.{table} ({columns}) values ({values})\n  on conflict ({key}) do update set {updates};"


